    private const val PREFS = "smart_lakbay_session"
    private const val KEY_LANG = "lang"

    fun getLang(context: Context): String {
        return context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY_LANG, "en") ?: "en"
    }

    fun setLang(context: Context, lang: String) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY_LANG, lang).apply()
    }

    fun t(context: Context, key: String): String {
        val lang = getLang(context)
        val dict = translations[lang] ?: translations["en"]!!
        return dict[key] ?: translations["en"]?.get(key) ?: key
    }

